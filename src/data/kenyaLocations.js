export function getConstituencies(countyName) {
  const county = kenyaLocations.find(c => c.county === countyName)
  return county ? county.constituencies : []
}

export function getWards(countyName, constituencyName) {
  const constituencies = getConstituencies(countyName)
  const constituency = constituencies.find(c => c.name === constituencyName)
  return constituency ? constituency.wards : []
}
